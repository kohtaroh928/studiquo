import type { Env } from "./env.ts";

/**
 * OpenAI proxy (Responses API, /v1/responses) — the base provider for every AI
 * feature. The app never holds `OPENAI_API_KEY`, only this Worker does.
 *
 * Model IDs are deliberately NOT hardcoded here: the logical models in ai.js's
 * `PLAN_MODELS` ("openai-luna" / "openai-terra" / "openai-sol" / "openai-astra")
 * are resolved to real ids via `env.OPENAI_LUNA_MODEL` / `OPENAI_TERRA_MODEL` /
 * `OPENAI_SOL_MODEL` / `OPENAI_ASTRA_MODEL` (plain `vars`; only
 * `OPENAI_API_KEY` is a secret), so a model change needs no code change.
 *
 * Safeguards for a student audience that may include minors: every request
 * carries `safety_identifier` (a hash of the account, never the account id) and
 * `store: false`; user-written text is screened with OpenAI's moderation
 * endpoint before it is sent (`moderationRejection`).
 */

const API_URL = "https://api.openai.com/v1/responses";
const MODERATION_URL = "https://api.openai.com/v1/moderations";
const RETRYABLE = new Set([429, 500, 502, 503, 504]);
const ATTEMPTS = 3;
// Reasoning tokens count against this too, so leave room beyond the visible answer.
const MAX_OUTPUT_TOKENS = 8192;

/** A user turn's content parts: its text, plus any images attached to it. */
function userContent(turn, images) {
  const parts: Record<string, unknown>[] = [{ type: "input_text", text: String(turn.text ?? "") }];
  for (const image of images) {
    parts.push({ type: "input_image", image_url: `data:image/png;base64,${image}`, detail: "auto" });
  }
  return parts;
}

/**
 * Builds the Responses API request body. Exported so tests can pin its shape.
 *
 * `store: false` keeps the conversation off OpenAI's side (ADR-0002): the
 * whole history is sent every turn, exactly as before, and
 * `previous_response_id` is never used. The system prompt goes in
 * `instructions`; assistant turns are plain strings (they were generated by
 * the model earlier), user turns are typed parts so images can ride along.
 */
export interface ResponsesBodyOptions {
  model: string;
  systemInstruction?: string;
  turns: { role: string; text?: unknown }[];
  images?: string[];
  safetyId?: unknown;
  schema?: unknown;
  schemaName?: string;
  maxOutputTokens?: number;
}

export function buildResponsesBody({
  model, systemInstruction, turns, images = [], safetyId, schema, schemaName, maxOutputTokens = MAX_OUTPUT_TOKENS,
}: ResponsesBodyOptions) {
  const lastIndex = turns.length - 1;
  const body: Record<string, unknown> = {
    model,
    instructions: systemInstruction,
    input: turns.map((turn, index) =>
      turn.role === "assistant"
        ? { role: "assistant", content: String(turn.text ?? "") }
        : { role: "user", content: userContent(turn, index === lastIndex ? images : []) },
    ),
    max_output_tokens: maxOutputTokens,
    stream: true,
    store: false,
  };
  if (safetyId) body.safety_identifier = String(safetyId).slice(0, 64);
  if (schema) {
    body.text = { format: { type: "json_schema", name: schemaName || "result", strict: true, schema: toStrictJSONSchema(schema) } };
  }
  return body;
}

/**
 * Accepts the schemas written in ai.js (upper-case OBJECT/STRING/… types, the
 * Gemini dialect they were first written in) and returns strict JSON Schema:
 * lower-case types, no extra properties, every property required.
 */
export function toStrictJSONSchema(schema: any): any {
  if (Array.isArray(schema)) return schema.map(toStrictJSONSchema);
  if (!schema || typeof schema !== "object") return schema;
  const out: Record<string, any> = {};
  for (const [name, value] of Object.entries(schema as Record<string, any>)) {
    if (name === "type" && typeof value === "string") out.type = value.toLowerCase();
    else if (name === "properties") out.properties = Object.fromEntries(Object.entries(value).map(([k, v]) => [k, toStrictJSONSchema(v)]));
    else if (name === "items") out.items = toStrictJSONSchema(value);
    else if (name !== "required") out[name] = value;
  }
  if (out.type === "object") {
    out.additionalProperties = false;
    out.required = Object.keys(out.properties ?? {});
  }
  return out;
}

/** Sends one Responses request, retrying overload/5xx with backoff. Returns the last response. */
async function postWithRetry(env: Env, body, apiKey) {
  if (!apiKey) throw new Error("OPENAI_API_KEY is not configured on this Worker.");
  const payload = JSON.stringify(body);
  let last = null;
  for (let attempt = 0; attempt < ATTEMPTS; attempt++) {
    if (attempt > 0) {
      const base = env.AI_RETRY_BASE_MS === undefined ? 600 : Number(env.AI_RETRY_BASE_MS) || 0;
      await new Promise(resolve => setTimeout(resolve, base * 2 ** (attempt - 1)));
    }
    const response = await fetch(API_URL, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: `Bearer ${apiKey}` },
      body: payload,
    });
    if (response.ok || !RETRYABLE.has(response.status)) {
      await last?.body?.cancel().catch(() => {});
      return response;
    }
    await last?.body?.cancel().catch(() => {});
    last = response;
  }
  return last;
}

/** Neutral content parts ({text} / {image: base64 PNG}) → Responses input parts. */
function toInputParts(parts) {
  return parts.map(part => part.image
    ? { type: "input_image", image_url: `data:image/png;base64,${part.image}`, detail: "auto" }
    : { type: "input_text", text: String(part.text ?? "") });
}

/** A structured (JSON schema) call whose single user message is made of `parts`. */
export async function callOpenAIStructured(env: Env, { model, systemInstruction, parts, schema, schemaName, safetyId, maxOutputTokens, apiKey = env.OPENAI_API_KEY }) {
  const body = buildResponsesBody({ model, systemInstruction, turns: [], safetyId, schema, schemaName, maxOutputTokens });
  body.input = [{ role: "user", content: toInputParts(parts) }];
  return postWithRetry(env, body, apiKey);
}

/**
 * `turns` is the same provider-agnostic shape ai.js's chat handler already
 * builds for Gemini (`{ role: "user" | "assistant", text }`). `images`
 * (already-validated PNG base64 strings) are attached to the last turn
 * only, matching how the app's own screenshot-attach flow works.
 *
 * `apiKey` defaults to this Worker's own `OPENAI_API_KEY`; it is a parameter
 * so a per-user token can be passed here later without touching the body.
 */
export async function callOpenAIChat(env: Env, { model, systemInstruction, turns, images = [], safetyId, apiKey = env.OPENAI_API_KEY }) {
  return postWithRetry(env, buildResponsesBody({ model, systemInstruction, turns, images, safetyId }), apiKey);
}

/**
 * Screens user-written text with OpenAI's moderation endpoint. Returns a
 * Japanese message when the text must not be sent, otherwise null. Self-harm
 * categories are let through on purpose (the model answers those with care
 * rather than the app refusing a student in distress). Fails closed: when the
 * screening cannot be done (the service is down, answers with an error or with
 * something unreadable) nothing is sent, and MODERATION_UNAVAILABLE is
 * returned instead of a message. Only `AI_MODERATION=off` skips the screening.
 */
export const MODERATION_UNAVAILABLE = Object.freeze({ unavailable: true });

export async function moderationRejection(env: Env, texts, apiKey = env.OPENAI_API_KEY) {
  if (env.AI_MODERATION === "off" || !apiKey) return null;
  const input = texts.map(text => String(text ?? "").slice(0, 8000)).filter(Boolean);
  if (input.length === 0) return null;
  try {
    const response = await fetch(MODERATION_URL, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: `Bearer ${apiKey}` },
      body: JSON.stringify({ model: "omni-moderation-latest", input }),
    });
    if (!response.ok) {
      await response.body?.cancel().catch(() => {});
      console.error(JSON.stringify({ message: "moderation unavailable", status: response.status }));
      return MODERATION_UNAVAILABLE;
    }
    const payload = (await response.json()) as { results?: { categories?: Record<string, unknown> }[] } | null;
    // An answer that does not say what was checked is no answer.
    if (!Array.isArray(payload?.results) || payload.results.length === 0) {
      console.error(JSON.stringify({ message: "moderation unreadable" }));
      return MODERATION_UNAVAILABLE;
    }
    for (const result of payload.results) {
      const hit = Object.entries(result?.categories ?? {}).some(([name, on]) => on && !name.startsWith("self-harm"));
      if (hit) return "この内容は学習アプリでは扱えません。表現を変えて、もう一度送信してください。";
    }
  } catch (error) {
    console.error(JSON.stringify({ message: "moderation failed", error: error instanceof Error ? error.message : String(error) }));
    return MODERATION_UNAVAILABLE;
  }
  return null;
}

/**
 * Pulls the incremental text out of one parsed Responses SSE event. Only
 * `response.output_text.delta` carries text; every other event (created,
 * output_item.*, completed, ...) yields "". Responses streams have no
 * terminal `[DONE]` line — ai.js's pump ends when the body ends.
 */
export function extractDeltaText(event) {
  if (event?.type !== "response.output_text.delta") return "";
  return typeof event.delta === "string" ? event.delta : "";
}
